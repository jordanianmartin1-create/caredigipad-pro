function checkShiftExpiry() {
  const st = localStorage.getItem('cdu_start');
  if (!st) return false;
  const ts = Number(st);
  if (st === '1' || isNaN(ts) || ts < 1000000000000) {
    localStorage.setItem('cdu_start', String(Date.now()));
    return false;
  }
  if (Date.now() - ts >= SHIFT_MAX_MS) {
    db = {};
    openForms = {};
    expandedCards = {};
    localStorage.removeItem('cdu_db');
    localStorage.removeItem('cdu_start');
    showSummary = false;
    showManageBed = false;
    showQuickAddBed = false;
    initSetup();
    return true;
  }
  return false;
}

function normalizeLayouts() {
  if (!layouts || typeof layouts !== 'object') { layouts = {}; return; }
  Object.keys(layouts).forEach(k => {
    const val = layouts[k];
    if (Array.isArray(val)) {
      layouts[k] = sortBedArray(val);
      return;
    }
    if (val && typeof val === 'object') {
      if (Array.isArray(val.alloc)) layouts[k] = sortBedArray(val.alloc);
      else if (Array.isArray(val.beds)) layouts[k] = sortBedArray(val.beds);
      else if (Array.isArray(val.ward)) layouts[k] = sortBedArray(val.ward);
      else delete layouts[k];
    } else delete layouts[k];
  });
  localStorage.setItem('cdu_layouts', JSON.stringify(layouts));
}
