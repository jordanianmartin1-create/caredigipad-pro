function getShiftHours() {
  const startHr = curShift === 'night' ? 19 : 7;
  const hrs = [];
  for (let i = 0; i < 12; i++) hrs.push(String((startHr + i) % 24).padStart(2, '0') + ':00');
  return hrs;
}

function getCurrentShiftHourIdx() {
  const curHrStr = String(new Date().getHours()).padStart(2, '0') + ':00';
  const hrs = getShiftHours();
  const idx = hrs.indexOf(curHrStr);
  return idx > -1 ? idx : 0;
}

