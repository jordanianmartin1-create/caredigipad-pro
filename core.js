function todayIsoStr() {
  const d = new Date();
  return d.getFullYear() + '-' + String(d.getMonth() + 1).padStart(2, '0') + '-' + String(d.getDate()).padStart(2, '0');
}

function formatIsoDate(isoStr) {
  if (!isoStr) return '';
  const p = isoStr.split('-');
  if (p.length !== 3) return isoStr;
  const dt = new Date(parseInt(p[0], 10), parseInt(p[1], 10) - 1, parseInt(p[2], 10));
  return isNaN(dt) ? isoStr : dt.toLocaleDateString(getLocaleCode(), { day: 'numeric', month: 'short', year: 'numeric' });
}

function calcDue(dateStr, days = 3) {
  if (!dateStr || !days) return '—';
  const p = dateStr.split('-');
  const dt = p.length === 3 ? new Date(parseInt(p[0], 10), parseInt(p[1], 10) - 1, parseInt(p[2], 10)) : new Date(dateStr);
  if (isNaN(dt)) return '—';
  dt.setDate(dt.getDate() + (parseInt(days, 10) || 3));
  return dt.toLocaleDateString(getLocaleCode(), { day: 'numeric', month: 'short', year: 'numeric' });
}

function nowTimeStr() {
  const d = new Date();
  return String(d.getHours()).padStart(2, '0') + ':' + String(d.getMinutes()).padStart(2, '0');
}

function sortModConfig() {
  if (!Array.isArray(modConfig)) return;
  const active = [];
  const inactive = [];
  const locked = [];
  modConfig.forEach(m => {
    const def = ALL_MODS.find(x => x.id === m.id);
    if (!def) return;
    if (def.pro && !isPro) locked.push(m);
    else if (m.on) active.push(m);
    else inactive.push(m);
  });
  modConfig = [...active, ...inactive, ...locked];
}

function initModConfig() {
  if (!Array.isArray(modConfig) || modConfig.length === 0) {
    modConfig = ALL_MODS.map(m => ({ id: m.id, on: !m.pro || isPro }));
  } else {
    ALL_MODS.forEach(m => {
      if (!modConfig.some(x => x.id === m.id)) {
        modConfig.push({ id: m.id, on: !m.pro || isPro });
      }
    });
  }
  if (!isPro) {
    modConfig.forEach(m => {
      const def = ALL_MODS.find(x => x.id === m.id);
      if (def && def.pro) m.on = false;
    });
    if (!modConfig.some(m => {
      const def = ALL_MODS.find(x => x.id === m.id);
      return def && !def.pro && m.on;
    })) {
      const firstFree = modConfig.find(m => m.id === 'obs');
      if (firstFree) firstFree.on = true;
    }
  }
  sortModConfig();
}

function getActiveSections() {
  initModConfig();
  return modConfig.filter(m => {
    const def = ALL_MODS.find(x => x.id === m.id);
    return def && (!def.pro || isPro) && m.on;
  });
}

